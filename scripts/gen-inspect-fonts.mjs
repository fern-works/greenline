// Regenerate src/shell/inspect/fonts.ts from greenline's own licensed copy
// of the fonts under assets/inspect-fonts/, so the inspector (docs/SPEC.md
// §4, ADR 0028) serves Geist offline from the CLI bundle with no network and
// no dependence on the website's files. The copy's licence, the SIL Open Font
// License 1.1 with its copyright line, is assets/inspect-fonts/OFL.txt, which
// ships in the package beside the bundle. The gate row `inspect-fonts`
// renders this module's output in memory and refuses drift between the two.
import { readFileSync, writeFileSync, mkdirSync, realpathSync, existsSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

/** The licensed copy's directory, relative to the checkout. */
export const INSPECT_FONTS = "assets/inspect-fonts";

/** The font files the module embeds and the licence that travels with them. */
export const INSPECT_FONT_FILES = [
  `${INSPECT_FONTS}/geist-var.woff2`,
  `${INSPECT_FONTS}/geist-mono-var.woff2`,
  `${INSPECT_FONTS}/OFL.txt`,
];

/** The generated module's text for the checkout at `root`. */
export function renderInspectFonts(root) {
  const sans = readFileSync(join(root, INSPECT_FONTS, "geist-var.woff2")).toString("base64");
  const mono = readFileSync(join(root, INSPECT_FONTS, "geist-mono-var.woff2")).toString("base64");
  const copyright = readFileSync(join(root, INSPECT_FONTS, "OFL.txt"), "utf8").split("\n")[0];
  return (
    `// Generated by scripts/gen-inspect-fonts.mjs from ${INSPECT_FONTS}; never edit.\n` +
    `// The inspector serves these offline (ADR 0028); the gate keeps them in step.\n` +
    `// Geist and Geist Mono: ${copyright}; the SIL Open Font License 1.1,\n` +
    `// whose text is ${INSPECT_FONTS}/OFL.txt in the repository and the package.\n\n` +
    `/** Geist, variable weight, woff2, base64. */\nexport const GEIST_SANS_BASE64: string =\n  "${sans}";\n\n` +
    `/** Geist Mono, variable weight, woff2, base64. */\nexport const GEIST_MONO_BASE64: string =\n  "${mono}";\n`
  );
}

// The guard compares physical paths: an absolute argv[1] through a symlink
// (macOS's /var and /tmp) would never equal the module's resolved URL, and
// the script would exit 0 having done nothing (stage N's third cold review).
if (
  process.argv[1] !== undefined &&
  existsSync(process.argv[1]) &&
  import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href
) {
  const root = new URL("..", import.meta.url).pathname;
  mkdirSync(join(root, "src/shell/inspect"), { recursive: true });
  const text = renderInspectFonts(root);
  writeFileSync(join(root, "src/shell/inspect/fonts.ts"), text);
  console.log(`fonts.ts written: ${text.length} chars`);
}
