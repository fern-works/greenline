import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import {
  DEFAULT_FILE_TOKENS,
  exemptionOf,
  fileTokensReport,
  markedGenerated,
  tokensOf,
} from "../../src/core/file-tokens.ts";
import { ok } from "../../src/commons/result.ts";
import { proposedChecks } from "../../src/core/checks.ts";
import { parseManifest, serializeManifest } from "../../src/core/manifest.ts";
import { runCheckCli } from "../../src/shell/cli/check.ts";
import { fixtureInstallation } from "../fixtures/corpus.ts";
import { RecordingWriter } from "../helpers/writer.ts";

/**
 * The file token cap (J-114 S4): a file's tokens counted as its bytes over
 * four, the standard exemptions and the manifest's own, the opt-in with
 * 5,000 as its default cap, and `greenline check files` on a real
 * repository: a file over the cap refused with how to split it, an exempt
 * one skipped, the staged files read by default.
 */

const cleanup: string[] = [];
afterEach(() => {
  for (const path of cleanup.splice(0)) rmSync(path, { recursive: true, force: true });
});

describe("J-114 S4 the count, the exemptions and the report", () => {
  it("counts a file's bytes over four, rounded up", () => {
    expect(tokensOf(0)).toBe(0);
    expect(tokensOf(4)).toBe(1);
    expect(tokensOf(20_001)).toBe(5001);
    expect(DEFAULT_FILE_TOKENS).toBe(5000);
  });

  it("exempts lockfiles, generated files, vendored trees and data, and the manifest's own globs first", () => {
    for (const [path, kind] of [
      ["pnpm-lock.yaml", "a lockfile"],
      ["apps/web/package-lock.json", "a lockfile"],
      ["Cargo.lock", "a lockfile"],
      ["dist/index.js", "a generated file"],
      ["public/app.min.js", "a generated file"],
      [".greenline/ledger/2026-10-25-a.md", "a generated file"],
      ["vendor/lib/a.go", "a vendored tree"],
      ["node_modules/x/index.js", "a vendored tree"],
      ["fixtures/rows.csv", "data"],
      ["docs/logo.svg", "data"],
    ] as const)
      expect([path, exemptionOf(path, [])?.kind]).toEqual([path, kind]);
    for (const path of ["src/app.ts", "README.md", "lib/vendored.ts", "src/dist.ts"])
      expect([path, exemptionOf(path, [])]).toEqual([path, undefined]);
    expect(exemptionOf("src/schema/generated.ts", ["src/schema/**"])).toEqual({
      glob: "src/schema/**",
      kind: "the manifest's exemption",
    });
    expect(exemptionOf("src/big.json", ["*.json"])?.glob).toBe("*.json");
  });

  it("reads a generator's mark in a file's first lines", () => {
    expect(markedGenerated("// Code generated by protoc. DO NOT EDIT.\npackage x")).toBe(true);
    expect(markedGenerated("/* @generated */\nexport {}")).toBe(true);
    expect(markedGenerated("export const a = 1;\n")).toBe(false);
    expect(markedGenerated(["1", "2", "3", "4", "5", "6 DO NOT EDIT"].join("\n"))).toBe(false);
  });

  it("refuses a file over the cap with its count and how to split it, and passes at the cap", () => {
    const report = fileTokensReport(
      [
        { path: "src/big.ts", kind: "counted", bytes: 24_000, tokens: 6000 },
        { path: "src/ok.ts", kind: "counted", bytes: 20_000, tokens: 5000 },
        { path: "pnpm-lock.yaml", kind: "exempt", why: "a lockfile, by pnpm-lock.yaml" },
      ],
      5000,
    );
    expect(report.green).toBe(false);
    expect(report.text).toBe(
      [
        "greenline check files: 2 files against 5000 tokens, 1 exempt; 1 over it",
        "  src/big.ts: about 6000 tokens (24000 bytes over four), over the cap of 5000; split it in a slice of its own: move one cohesive part, a group of functions, a type and its parsers, a section, into a file of its own beside it, keep each file under the cap, and commit the move before any other change to either",
        "",
      ].join("\n"),
    );
    expect(fileTokensReport([], 5000)).toEqual({
      text: "greenline check files: 0 files against 5000 tokens, 0 exempt; each under the cap\n",
      green: true,
    });
  });

  it("declares nothing with the opt-in off: init proposes no file token check from a project's files", () => {
    const proposed = proposedChecks({
      packageJson: JSON.stringify({ scripts: { test: "vitest", lint: "oxlint", build: "tsc" } }),
      makefile: undefined,
      cargoToml: undefined,
      pyprojectToml: undefined,
      goMod: undefined,
      lockFiles: ["pnpm-lock.yaml"],
    });
    expect(proposed.map((check) => check.command)).not.toContainEqual(
      expect.stringContaining("check files"),
    );
  });

  it("takes the manifest's opt-in, its cap 5,000 by default, written only where it is set", () => {
    const base = { schemaVersion: 6, targets: ["codex"] };
    const on = parseManifest(JSON.stringify({ ...base, fileTokens: {} }), "m");
    expect(on._tag === "ok" ? on.value.fileTokens : undefined).toEqual({ cap: 5000, exempt: [] });
    if (on._tag === "ok") expect(serializeManifest(on.value)).toContain('"fileTokens": {');
    const off = parseManifest(JSON.stringify(base), "m");
    expect(off._tag === "ok" ? off.value.fileTokens : "read").toBeUndefined();
    if (off._tag === "ok") expect(serializeManifest(off.value)).not.toContain("fileTokens");
    for (const wrong of [{ cap: 0 }, { cap: 1.5 }, { cap: 5000, other: true }])
      expect([
        wrong,
        parseManifest(JSON.stringify({ ...base, fileTokens: wrong }), "m")._tag,
      ]).toEqual([wrong, "err"]);
  });
});

describe("J-114 S4 greenline check files on a real repository", () => {
  /** The manifest's file token setting as a test writes it. */
  interface Written {
    readonly fileTokens?: { readonly cap?: number; readonly exempt?: readonly string[] };
  }
  function repository(manifest: Written = {}): string {
    const root = mkdtempSync(join(tmpdir(), "check-files-"));
    cleanup.push(root);
    execFileSync("git", ["init", "--quiet", "-b", "main"], { cwd: root });
    mkdirSync(join(root, ".greenline"), { recursive: true });
    writeFileSync(
      join(root, ".greenline", "manifest.json"),
      JSON.stringify({ schemaVersion: 6, targets: ["claude-code"], ...manifest }),
    );
    return root;
  }
  const files = async (root: string, ...argv: string[]) => {
    const writer = new RecordingWriter();
    const code = await runCheckCli(["files", ...argv], writer.writer, {
      cwd: root,
      installation: () => ok(fixtureInstallation()),
      environment: process.env,
      stdio: "pipe",
    });
    return { code, out: writer.out, err: writer.err };
  };

  it("refuses a staged file over the cap with how to split it, skips an exempt one, and passes the rest", async () => {
    const root = repository();
    writeFileSync(join(root, "big.ts"), "x".repeat(20_004));
    writeFileSync(join(root, "small.ts"), "export {};\n");
    writeFileSync(join(root, "pnpm-lock.yaml"), "y".repeat(40_000));
    execFileSync("git", ["add", "big.ts", "small.ts", "pnpm-lock.yaml"], { cwd: root });
    const red = await files(root);
    expect(red.code).toBe(1);
    expect(red.out).toContain(
      "greenline check files: 2 files against 5000 tokens, 1 exempt; 1 over it\n",
    );
    expect(red.out).toContain(
      "  big.ts: about 5001 tokens (20004 bytes over four), over the cap of 5000; split it in a slice of its own:",
    );
    expect((await files(root, "--max-tokens", "6000")).code).toBe(0);
    expect((await files(root, "small.ts")).code).toBe(0);
  });

  it("reads the manifest's cap and its exemptions, and the working tree's files where none is staged", async () => {
    const root = repository({ fileTokens: { cap: 10, exempt: ["gen/**"] } });
    writeFileSync(join(root, "a.ts"), "x".repeat(44));
    mkdirSync(join(root, "gen"));
    writeFileSync(join(root, "gen", "b.ts"), "x".repeat(400));
    const red = await files(root);
    expect(red.code).toBe(1);
    expect(red.out).toContain("against 10 tokens");
    expect(red.out).toContain("  a.ts: about 11 tokens");
    expect(red.out).not.toContain("gen/b.ts: about");
  });

  it("refuses arguments it does not read with the usage code", async () => {
    const root = repository();
    expect((await files(root, "--max-tokens", "lots")).code).toBe(2);
    expect((await files(root, "--other")).code).toBe(2);
    expect((await files(root, "../outside.ts")).code).toBe(2);
  });
});
