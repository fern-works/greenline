import type { WordsSource } from "../core/corpus.ts";
import { LOAD_VERDICTS, type Drop, type LoadVerdict } from "./recipe.ts";
import { cell, table } from "./tables.ts";

/**
 * The dismissal view (J-182 S1, `workshop/components/ledger.md`, "The
 * views"): every segment a roster recipe drops, as the dismissals a run's
 * finding is read against. A dismissal is the segments of one source file a
 * recipe drops on one account, its kind and its reason and, once the load
 * test has read the passage, its verdict and the failure that test named.
 * The dismissals the load test read stand apart from those dropped before
 * it, so a finding is matched against a named failure first. Pure functions
 * over the parsed recipes, rendered as `corpus/ledger/DISMISSALS.md`.
 */

/** One skill's drops, as its recipe lists them. */
export interface SkillDrops {
  readonly skill: string;
  readonly drops: readonly Drop[];
}

/** The segments of one source file a recipe drops on one account. */
interface Dismissal {
  readonly skill: string;
  readonly at: string;
  readonly kind: string;
  readonly reason: string;
  readonly verdict: LoadVerdict | undefined;
  readonly failure: string | undefined;
  segments: number;
}

/**
 * The dismissals of each skill, in skill order and then in the order the
 * recipe first names each account.
 * @param skills each skill's drops
 * @returns one dismissal per skill, source file and account
 */
function dismissalsOf(skills: readonly SkillDrops[]): readonly Dismissal[] {
  const out: Dismissal[] = [];
  for (const { skill, drops } of [...skills].sort((a, b) => a.skill.localeCompare(b.skill))) {
    const byAccount = new Map<string, Dismissal>();
    for (const drop of drops) {
      const at = `${drop.source}/${drop.file}`;
      const key = JSON.stringify([at, drop.kind, drop.reason, drop.verdict, drop.failure]);
      const known = byAccount.get(key);
      if (known !== undefined) known.segments += 1;
      else {
        const dismissal: Dismissal = {
          skill,
          at,
          kind: drop.kind,
          reason: drop.reason,
          verdict: drop.verdict,
          failure: drop.failure,
          segments: 1,
        };
        byAccount.set(key, dismissal);
        out.push(dismissal);
      }
    }
  }
  return out;
}

/**
 * A reason or a failure as a table cell: its pipes escaped, and its
 * emphasis marks outside code spans escaped, so the formatter reads a
 * recipe's prose as written and leaves the view as rendered.
 * @param text the prose a recipe states
 * @returns the cell's text
 */
function prose(text: string): string {
  return cell(
    text
      .split("`")
      .map((part, index) => (index % 2 === 1 ? part : part.replace(/[*_]/g, (mark) => `\\${mark}`)))
      .join("`"),
  );
}

/** A count of skills in words: "1 skill", "2 skills". */
const skillCount = (count: number) => `${count} skill${count === 1 ? "" : "s"}`;

/** The sum of the dismissals' segments. */
const segmentsOf = (items: readonly Dismissal[]) =>
  items.reduce((sum, item) => sum + item.segments, 0);

/**
 * The ledger's dismissal view: its head counts the dismissed segments, those
 * the load test read by verdict and with a failure named, and those dropped
 * before it; then one row per dismissal the load test read, with its
 * verdict, its failure and its reason; then one row per dismissal before
 * the load test, under its skill's heading, with its kind and its reason.
 * @param skills each skill's drops
 * @returns the text of `corpus/ledger/DISMISSALS.md`
 */
export function renderDismissals(
  skills: readonly SkillDrops[],
  words: readonly WordsSource[] = [],
): string {
  const all = dismissalsOf(skills);
  const read = all.filter((item) => item.verdict !== undefined);
  const before = all.filter((item) => item.verdict === undefined);
  const byVerdict = LOAD_VERDICTS.map(
    (verdict) => `${verdict} ${segmentsOf(read.filter((item) => item.verdict === verdict))}`,
  ).join(", ");
  const named = segmentsOf(read.filter((item) => item.failure !== undefined));
  const dismissing = new Set(all.map((item) => item.skill)).size;
  const lines = [
    "# The dismissals",
    "",
    "Generated by `node scripts/corpus.mjs views` from each recipe's `drops` under `corpus/recipes/`, and never edited by hand. A dismissal is the segments of one source file a recipe does not take on one account: its kind and its reason and, once the load test has read the passage, its verdict and the failure that test named. The load test reads a passage with the agent at the moment it would read it, with the passage and without, and gives one of four verdicts: load-bearing, kept whole; scaffolding, kept with the passage it carries; duplicate, a passage the roster already states; or decoration, which changes nothing the agent does. A run's finding is read against the failures named here: a finding whose failure a dismissal names takes the passage back into its skill, the run cited as its case.",
    "",
    "## The counts",
    "",
    `- Dismissed segments: ${segmentsOf(all)}, across ${skillCount(dismissing)}.`,
    `- Read by the load test: ${segmentsOf(read)}, by verdict ${byVerdict}; with a failure named ${named}.`,
    `- Before the load test: ${segmentsOf(before)}, each with its kind and its reason and no verdict.`,
    "",
    "## Read by the load test",
    "",
    read.length === 0
      ? "No dismissal has been read by the load test yet."
      : table(
          ["Skill", "Source and file", "Segments", "Verdict", "Failure", "Reason"],
          read.map((item) => [
            `\`${item.skill}\``,
            `\`${item.at}\``,
            String(item.segments),
            item.verdict ?? "",
            prose(item.failure ?? "none named"),
            prose(item.reason),
          ]),
        ),
    "",
    "## Before the load test",
    "",
    ...(before.length === 0
      ? ["Every dismissal has been read by the load test."]
      : [...new Set(before.map((item) => item.skill))].flatMap((skill) => [
          `### \`${skill}\``,
          "",
          table(
            ["Source and file", "Segments", "Kind", "Reason"],
            before
              .filter((item) => item.skill === skill)
              .map((item) => [
                `\`${item.at}\``,
                String(item.segments),
                item.kind,
                prose(item.reason),
              ]),
          ),
          "",
        ])),
  ];
  // The phrases' section follows after one blank line, whatever the last table left (J-195 S1).
  const phrases = dismissedPhrases(words);
  const body = lines.join("\n").trimEnd();
  return `${phrases.length === 0 ? body : [body, ...phrases].join("\n")}\n`;
}

/**
 * The phrases dismissed (J-194 S1), each with the failure the fit craft
 * named; nothing where no phrase is dismissed, so the view is as before.
 * @param words the manifest's words sources
 * @returns the section's lines
 */
function dismissedPhrases(words: readonly WordsSource[]): readonly string[] {
  const rows = words.flatMap((source) =>
    source.phrases.flatMap((phrase) =>
      phrase.dismissed === undefined
        ? []
        : [
            [
              prose(phrase.text),
              `\`${source.name}\``,
              phrase.date,
              prose(phrase.dismissed.failure),
            ],
          ],
    ),
  );
  return rows.length === 0
    ? []
    : ["", "## Dismissed phrases", "", table(["Phrase", "Source", "Date", "Failure"], rows)];
}
